const assert=require('node:assert/strict');
const {chromium}=require('playwright');
const QRCode=require('qrcode');
const model=require('../public/inspection-model');
const path=require('path');
const fs=require('fs');
(async()=>{
  const browser=await chromium.launch({channel:'chrome',headless:true});
  try{
    const context=await browser.newContext({viewport:{width:1440,height:1000}});
    const page=await context.newPage();let saved=null;const errors=[];let uploads=0;
    page.on('pageerror',error=>errors.push(error.message));
    await page.route('**/supabase-js@2',route=>route.fulfill({contentType:'application/javascript',body:`window.supabase={createClient:()=>({from:(table)=>{let q=new Proxy({},{get:(_,key)=>key==='then'?(resolve)=>Promise.resolve({data:table==='buses'?[{id:'B1',plate:'30-1111 สข'}]:[],error:null}).then(resolve):()=>q});return q;}})};`}));
    await page.route('**/.netlify/functions/**',async route=>{
      const req=route.request(),url=new URL(req.url());
      if(!url.pathname.endsWith('vehicle-inspections'))return route.fulfill({json:{success:true,used:0,limit:300,remaining:300}});
      if(req.method()==='GET')return route.fulfill({json:url.searchParams.has('id')?{success:true,record:saved,canEdit:saved.state==='draft'}:{success:true,records:saved?[{...saved,...model.summary(saved)}]:[]}});
      const body=req.postDataJSON();
      if(body.action==='upload'){uploads++;return route.fulfill({json:{success:true,attachment:{path:`test/${body.id}/signature.png`,target:body.target,url:'data:image/png;base64,'+body.base64}}});}
      assert.equal(body.action,'save');
      saved={...model.normalize(body.record,body.state==='submitted'),id:body.id,revision:(saved?.revision||0)+1,number:'VI-TEST',state:body.state,attachments:body.record.attachments||[],submittedAt:'2026-11-05T01:30:00Z',submittedBy:'Tester'};
      return route.fulfill({json:{success:true,id:saved.id,revision:saved.revision,number:saved.number}});
    });
    await page.addInitScript(()=>{sessionStorage.setItem('currentUser',JSON.stringify({id:'test',name:'Tester',username:'tester',role:'admin'}));sessionStorage.setItem('appSessionToken','test');});
    await page.goto(process.env.TEST_URL||'http://localhost:5180');
    await page.locator('.sidebar-nav-item[data-page="inspections"]').click();
    await page.waitForFunction(()=>document.querySelectorAll('#vi-bus-list option').length===1);
    assert.ok((await page.locator('#vi-count').innerText()).includes('0 ครั้งตรวจ'));
    await page.locator('button[onclick="InspectionUI.newRecord()"]' ).click();
    await page.locator('#vi-plate').fill('30-1111 สข');await page.locator('#vi-route').fill('ทดสอบเส้นทาง');await page.locator('#vi-driver1').fill('คนขับทดสอบ');
    await page.locator('button[onclick="InspectionUI.save(\'draft\')"]').click();
    await page.waitForFunction(()=>document.getElementById('vi-title').textContent==='VI-TEST');
    assert.equal(saved.state,'draft');
    for(const input of await page.locator('.vi-choice.pass input').all())await input.check({force:true});
    for(const input of await page.locator('.vi-count input').all())await input.fill('2');
    const folder=path.resolve('tmp/inspection-ui');fs.mkdirSync(folder,{recursive:true});
    await page.evaluate(()=>window.scrollTo(0,0));await page.waitForTimeout(400);
    await page.screenshot({path:path.join(folder,'desktop.png')});
    await page.setViewportSize({width:390,height:844});
    await page.waitForTimeout(500);
    await page.screenshot({path:path.join(folder,'mobile.png')});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2),'mobile viewport overflow');
    const qr=await QRCode.toDataURL('30-1111 สข');
    const decoded=await page.evaluate(async url=>{
      const div=document.createElement('div');div.id='test-qr';document.body.appendChild(div);
      const blob=await(await fetch(url)).blob();const reader=new Html5Qrcode('test-qr');
      const text=await reader.scanFile(new File([blob],'qr.png',{type:'image/png'}),false);reader.clear();div.remove();return text;
    },qr);
    assert.equal(decoded,'30-1111 สข');
    await page.locator('#vi-sign-button-inspector').click();
    await page.waitForTimeout(200);
    const pad=await page.locator('#vi-sign-full').boundingBox();
    await page.mouse.move(pad.x+25,pad.y+25);await page.mouse.down();await page.mouse.move(pad.x+100,pad.y+50,{steps:5});await page.mouse.up();
    const ink=()=>page.evaluate(()=>{const c=document.getElementById('vi-sign-full');return c.getContext('2d').getImageData(0,0,c.width,c.height).data.some((value,index)=>index%4===3&&value>0);});
    assert.ok(await ink());
    await page.setViewportSize({width:844,height:390});await page.waitForTimeout(350);
    assert.ok(await ink(),'rotating to landscape must retain strokes');
    const rect=await page.locator('#vi-sign-dialog').boundingBox();assert.equal(rect.width,844);assert.equal(rect.height,390);
    await page.screenshot({path:path.join(folder,'signature-landscape.png')});
    await page.locator('#vi-sign-dialog [data-action="use"]').click();
    assert.equal(await page.locator('#vi-sign-dialog').count(),0);
    const prior=await page.locator('#vi-pad-inspector').evaluate(c=>c.toDataURL());
    await page.locator('#vi-sign-button-inspector').click();
    await page.locator('#vi-sign-dialog [data-action="clear"]').click();
    await page.locator('#vi-sign-dialog [data-action="use"]').click();
    assert.equal(await page.locator('#vi-sign-dialog').count(),1,'blank signature must not be accepted');
    await page.locator('#vi-sign-dialog [data-action="cancel"]').click();
    assert.equal(await page.locator('#vi-pad-inspector').evaluate(c=>c.toDataURL()),prior,'cancel preserves the previous signature');
    await page.setViewportSize({width:390,height:844});await page.waitForTimeout(300);
    await page.locator('#vi-save-actions button[type="submit"]').click();
    await page.locator('.swal2-confirm').click();
    await page.waitForFunction(()=>document.getElementById('vi-save-actions').classList.contains('d-none'));
    assert.equal(saved.state,'submitted');assert.equal(await page.locator('#vi-driver1').isDisabled(),true);
    assert.equal(uploads,1);assert.equal(saved.attachments[0].target,'signature-inspector');
    const popupPromise=context.waitForEvent('page');
    await page.locator('button[onclick="InspectionUI.print()"]' ).click();
    const popup=await popupPromise;await popup.waitForLoadState();
    assert.ok((await popup.locator('body').innerText()).includes('คนขับทดสอบ'));
    await popup.close();
    await page.locator('button[onclick="InspectionUI.back()"]' ).click();
    await page.evaluate(()=>window.scrollTo(0,0));await page.waitForTimeout(300);
    await page.screenshot({path:path.join(folder,'mobile-history.png')});
    await page.locator('button[onclick="InspectionUI.newRecord()"]' ).click();
    await page.locator('button[onclick="InspectionUI.nextUnchecked(true)"]').click();
    await page.waitForTimeout(500);
    assert.equal(await page.locator('.vi-group[open]').count(),1);
    const first=page.locator('.vi-group').first();
    await first.locator('.vi-choice.pass input').first().check({force:true});
    await page.locator('button[data-mode="fail"]').click();
    assert.equal(await page.locator('#vi-check-empty').isVisible(),true);
    await page.locator('button[data-mode="all"]').click();
    await page.locator('button[onclick="InspectionUI.nextUnchecked()"]').click();
    await page.waitForTimeout(400);
    await page.screenshot({path:path.join(folder,'mobile-checklist.png')});
    for(const width of [360,390,430]){
      await page.setViewportSize({width,height:844});await page.waitForTimeout(300);
      assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2),`overflow at ${width}`);
      assert.ok(await page.locator('#vi-save-actions').isVisible());
    }
    assert.equal(errors.length,0,errors.join('\n'));
    console.log('PASS: desktop/mobile form, draft/submit, read-only result, real QR decode, print preview; all database/network writes mocked');
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
